const UNIT_BY_CODE = new Map(PRICE_SHEET_UNITS.map((unit) => [unit.code, unit]));

export function findPriceSheetUnit(code: string): PriceSheetUnit | undefined {
  return UNIT_BY_CODE.get(code.trim().toUpperCase());
}

/** Match mã căn as typed: "815", "ch0815", "CH-0815". */
export function searchPriceSheetUnits(query: string, limit = 8): PriceSheetUnit[] {
  const raw = query.trim().toLowerCase();
  if (!raw) return PRICE_SHEET_UNITS.slice(0, limit);
  const needle = raw.replace(/[^a-z0-9]/g, "");
  const starts: PriceSheetUnit[] = [];
  const rest: PriceSheetUnit[] = [];
  for (const unit of PRICE_SHEET_UNITS) {
    const code = unit.code.toLowerCase().replace(/[^a-z0-9]/g, "");
    if (code.startsWith(needle)) starts.push(unit);
    else if (code.includes(needle)) rest.push(unit);
    if (starts.length >= limit) break;
  }
  return [...starts, ...rest].slice(0, limit);
}
